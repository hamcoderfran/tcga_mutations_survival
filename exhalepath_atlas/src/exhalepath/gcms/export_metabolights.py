"""Lightweight mzTab-M + ISA-Tab exports for MetaboLights-oriented deposits.

These are research-enablement scaffolds (not a full mzTab-M validator).
They serialize patient×VOC intensity tables + sample metadata into formats
MetaboLights / ISA tooling can ingest after curator review.
"""

from __future__ import annotations

import csv
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .patient_matrix import PatientVOCMatrix


def export_mztab_m(matrix: PatientVOCMatrix, out_path: Path) -> Path:
    """Write a minimal mzTab-M-like TSV (metadata + small molecule section)."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    lines.append("MTD\tmzTab-version\t2.0.0-M")
    lines.append(f"MTD\tmzTab-ID\t{matrix.study_id}")
    lines.append(f"MTD\ttitle\t{matrix.disease_name} exhaled VOC intensities")
    lines.append(
        f"MTD\tdescription\tExhalePath Atlas export · modality={matrix.modality} · unit={matrix.unit}"
    )
    lines.append(f"MTD\tURI\thttps://github.com/hamcoderfran/tcga_mutations_survival")
    doi = (matrix.metadata or {}).get("doi")
    if doi:
        lines.append(f"MTD\texternal_study\tdoi:{doi}")
    lines.append(f"MTD\tcreation_date\t{datetime.now(timezone.utc).date().isoformat()}")
    lines.append(
        "MTD\tquantification_method\t[MS, MS:1001838, derived peak intensity, ]"
    )
    # assay ids = subjects
    for i, sid in enumerate(matrix.subject_ids, 1):
        lines.append(f"MTD\tassay[{i}]-name\t{sid}")
        lab = "disease" if int(matrix.labels.loc[sid]) == 1 else "control"
        lines.append(f"MTD\tassay[{i}]-custom[1]\t[,,sample label, {lab}]")
    lines.append("")
    # SMH header
    header = [
        "SMH",
        "SML_ID",
        "SMF_ID_REFS",
        "database_identifier",
        "chemical_name",
        "abundance_assay",
    ]
    # expand abundance columns
    assay_cols = [f"abundance_assay[{i}]" for i in range(1, len(matrix.subject_ids) + 1)]
    header = [
        "SMH",
        "SML_ID",
        "database_identifier",
        "chemical_name",
        *assay_cols,
    ]
    lines.append("\t".join(header))
    for j, voc in enumerate(matrix.matrix.columns, 1):
        row = [
            "SML",
            str(j),
            f"VOC:{voc}",
            str(voc),
        ]
        for sid in matrix.subject_ids:
            val = matrix.matrix.loc[sid, voc]
            row.append(f"{float(val):.6g}")
        lines.append("\t".join(row))
    out_path.write_text("\n".join(lines) + "\n")
    return out_path


def export_isa_tab(matrix: PatientVOCMatrix, out_dir: Path) -> dict[str, Path]:
    """Write minimal ISA-Tab investigation/study/assay + sample metadata TSV."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}

    inv = out_dir / "i_Investigation.txt"
    inv.write_text(
        "\n".join(
            [
                "ONTOLOGY SOURCE REFERENCE",
                "Term Source Name\tNCBITaxon\tUO",
                "INVESTIGATION",
                f"Investigation Identifier\t{matrix.study_id}",
                f"Investigation Title\t{matrix.disease_name} exhaled VOC study export",
                "Investigation Description\tGenerated by ExhalePath Atlas / voc-breath for MetaboLights prep",
                f"Investigation Submission Date\t{datetime.now(timezone.utc).date().isoformat()}",
                "INVESTIGATION PUBLICATIONS",
                f"Investigation PubMed ID\t",
                f"Investigation Publication DOI\t{(matrix.metadata or {}).get('doi') or ''}",
                "STUDY",
                f"Study Identifier\t{matrix.study_id}",
                f"Study Title\t{matrix.disease_name}",
                f"Study Description\tmodality={matrix.modality}; unit={matrix.unit}",
                "Study File Name\ts_samples.txt",
                "STUDY DESIGN DESCRIPTORS",
                "Study Design Type\tbreathomics case-control",
                "STUDY ASSAYS",
                "Study Assay Measurement Type\tmetabolite profiling",
                "Study Assay Technology Type\tmass spectrometry",
                "Study Assay Technology Platform\tGC-MS",
                "Study Assay File Name\ta_assay.txt",
                "",
            ]
        )
    )
    paths["investigation"] = inv

    s_path = out_dir / "s_samples.txt"
    with s_path.open("w", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(
            [
                "Source Name",
                "Characteristics[organism]",
                "Characteristics[sex]",
                "Characteristics[age]",
                "Characteristics[smoking_status]",
                "Characteristics[disease]",
                "Factor Value[disease_status]",
            ]
        )
        for rec in matrix.samples:
            status = "disease" if int(matrix.labels.loc[rec.subject_id]) == 1 else "control"
            w.writerow(
                [
                    rec.subject_id,
                    "Homo sapiens",
                    rec.sex or "",
                    "" if rec.age is None else rec.age,
                    rec.smoking_status or "",
                    rec.disease_id or matrix.disease_id,
                    status,
                ]
            )
    paths["study"] = s_path

    a_path = out_dir / "a_assay.txt"
    with a_path.open("w", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(
            [
                "Sample Name",
                "Protocol REF",
                "Parameter Value[modality]",
                "Raw Spectral Data File",
            ]
        )
        for sid in matrix.subject_ids:
            w.writerow([sid, "VOC intensity table", matrix.modality, "patient_voc_matrix.csv"])
    paths["assay"] = a_path

    # also dump the intensity matrix beside ISA files
    mat = out_dir / "patient_voc_matrix.csv"
    matrix.matrix.to_csv(mat)
    paths["matrix"] = mat
    return paths


def export_metabolights_bundle(matrix: PatientVOCMatrix, out_dir: Path) -> dict[str, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = export_isa_tab(matrix, out_dir / "isa")
    paths["mztab"] = export_mztab_m(matrix, out_dir / f"{matrix.study_id}.mzTab")
    readme = out_dir / "README_METABOLIGHTS.md"
    readme.write_text(
        "\n".join(
            [
                "# MetaboLights-oriented export (scaffold)",
                "",
                "Generated by `voc export-metabolights`.",
                "",
                "- `isa/` — minimal ISA-Tab investigation/study/assay",
                f"- `{matrix.study_id}.mzTab` — lightweight mzTab-M-like intensity table",
                "",
                "Review and complete ontology terms / protocols before deposit.",
                f"DOI hint: {(matrix.metadata or {}).get('doi')}",
                "",
            ]
        )
    )
    paths["readme"] = readme
    return paths
